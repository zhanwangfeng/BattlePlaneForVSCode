export const I18N: Record<Lang, Record<string, string>> = { cn: CN, en: EN };

export function langOf(): Lang {
  let env = '';
  try {
    const raw = process.env.VSCODE_NLS_CONFIG;
    if (raw) {
      const cfg = JSON.parse(raw);
      env = (cfg.locale as string) || '';
    }
  } catch {
    env = '';
  }
  if (!env && typeof (process.env as any).LANG === 'string') env = (process.env as any).LANG;
  return /zh|cn/i.test(env) ? 'cn' : 'en';
}

export function t(lang: Lang, key: string, map?: Record<string, string | number>): string {
  const d = I18N[lang] || CN;
  let s: string = d[key] ?? CN[key] ?? key;
  if (map) {
    for (const k of Object.keys(map)) s = s.split('{' + k + '}').join(String(map[k]));
  }
  return s;
}

export function dictFor(lang: Lang): Record<string, string> {
  return I18N[lang] || CN;
}
